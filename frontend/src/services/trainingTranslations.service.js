/**
 * Get translated content for a training resource
 */
export function getTranslatedResource(resource, lang) {
  if (!resource || !lang || lang === 'en') return resource;
  
  const langData = TRAINING_TRANSLATIONS[lang];
  if (!langData) return resource;

  const resKey = resource.title;
  const override = langData.resources?.[resKey];

  if (override) {
    return {
      ...resource,
      title: override.title || resource.title,
      summary: override.summary || resource.summary,
      content: override.content || resource.content,
      keyTakeaways: override.keyTakeaways || resource.keyTakeaways,
      practicalSteps: override.practicalSteps || resource.practicalSteps,
      category: langData.categoryDbLabels?.[resource.category] || resource.category
    };
  }

  return {
    ...resource,
    category: langData.categoryDbLabels?.[resource.category] || resource.category
  };
}
