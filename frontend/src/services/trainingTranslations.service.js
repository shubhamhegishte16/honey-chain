export function getTranslatedResource(resource, language = 'en') {
  if (!resource) return null;
  if (language === 'en') return resource;

  const transDict = TRAINING_TRANSLATIONS[language];
  if (!transDict) return resource;

  const translatedCat = transDict.categoryDbLabels?.[resource.category] || resource.category;

  return {
    ...resource,
    category: translatedCat,
    translatedCategory: translatedCat,
  };
}

